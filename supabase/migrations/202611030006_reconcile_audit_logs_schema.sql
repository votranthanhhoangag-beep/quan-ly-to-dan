begin;

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  event_id uuid,
  actor_user_id uuid references auth.users (id) on delete set null,
  username text,
  role text,
  action_type text,
  module_name text,
  description text,
  target_id text,
  created_at timestamptz
);

alter table public.audit_logs
  add column if not exists id bigint generated by default as identity,
  add column if not exists event_id uuid,
  add column if not exists actor_user_id uuid references auth.users (id) on delete set null,
  add column if not exists username text,
  add column if not exists role text,
  add column if not exists action_type text,
  add column if not exists module_name text,
  add column if not exists description text,
  add column if not exists target_id text,
  add column if not exists created_at timestamptz;

update public.audit_logs as audit_log
set
  username = coalesce(nullif(trim(audit_log.username), ''), profile.username, 'unknown'),
  role = case
    when audit_log.role in ('admin', 'ke_toan', 'kho_to_dan') then audit_log.role
    when profile.role in ('admin', 'ke_toan', 'kho_to_dan') then profile.role
    else 'kho_to_dan'
  end,
  action_type = case
    when audit_log.action_type in ('CREATE', 'UPDATE', 'DELETE') then audit_log.action_type
    else 'CREATE'
  end,
  module_name = coalesce(nullif(trim(audit_log.module_name), ''), 'unknown'),
  description = coalesce(audit_log.description, ''),
  target_id = coalesce(audit_log.target_id, ''),
  event_id = coalesce(audit_log.event_id, gen_random_uuid()),
  created_at = coalesce(audit_log.created_at, now())
from public.user_profiles as profile
where profile.user_id = audit_log.actor_user_id;

update public.audit_logs
set
  username = coalesce(nullif(trim(username), ''), 'unknown'),
  role = case when role in ('admin', 'ke_toan', 'kho_to_dan') then role else 'kho_to_dan' end,
  action_type = case when action_type in ('CREATE', 'UPDATE', 'DELETE') then action_type else 'CREATE' end,
  module_name = coalesce(nullif(trim(module_name), ''), 'unknown'),
  description = coalesce(description, ''),
  target_id = coalesce(target_id, ''),
  event_id = coalesce(event_id, gen_random_uuid()),
  created_at = coalesce(created_at, now());

with duplicate_event_ids as (
  select
    ctid,
    row_number() over (partition by event_id order by ctid) as duplicate_number
  from public.audit_logs
)
update public.audit_logs as audit_log
set event_id = gen_random_uuid()
from duplicate_event_ids
where audit_log.ctid = duplicate_event_ids.ctid
  and duplicate_event_ids.duplicate_number > 1;

alter table public.audit_logs
  alter column event_id set default gen_random_uuid(),
  alter column event_id set not null,
  alter column username set default 'unknown',
  alter column username set not null,
  alter column role set default 'kho_to_dan',
  alter column role set not null,
  alter column action_type set default 'CREATE',
  alter column action_type set not null,
  alter column module_name set default 'unknown',
  alter column module_name set not null,
  alter column description set default '',
  alter column description set not null,
  alter column target_id set default '',
  alter column target_id set not null,
  alter column created_at set default now(),
  alter column created_at set not null;

create unique index if not exists audit_logs_event_id_key
  on public.audit_logs (event_id);

create index if not exists audit_logs_actor_user_id_idx
  on public.audit_logs (actor_user_id);

create index if not exists audit_logs_created_at_idx
  on public.audit_logs (created_at desc);

alter table public.audit_logs enable row level security;

notify pgrst, 'reload schema';

commit;
